"""Explicit one-shot Main application account + COD setup, no business fixtures.

Uses the two immutable SQL templates. Password is generated by MySQL, captured in
RAM and immediately saved outside Git in a pre-reserved ACL-protected option file.
On failure: journal partial state, STOP, no reset/retry/drop/database cleanup.
"""
from pathlib import Path
import argparse
import base64
import configparser
from datetime import datetime,timezone,timedelta
import hashlib
import json
import os
import re
import subprocess
import sys
import mysql_baseline as m
import run_main_jpa_validate as jpa

UUID='c89cf662-c8bc-11f1-bc80-40c2ba627c1b'
APP='fooddelivery_app'
ACTOR="'fooddelivery_app'@'127.0.0.1'"
PRIVILEGES={'SELECT','INSERT','UPDATE','DELETE'}

def scripts():
    pinned=json.loads((m.ROOT/'docs/coursework/sql-reorganization-checksums.json').read_text(encoding='utf-8'))['files']
    result={};hashes={}
    for name in ['002_fooddelivery_app.sql','003_cod.sql']:
        path=m.ROOT/'database/setup'/name;raw=path.read_bytes()
        expected=next(x['beforeSha256'] for x in pinned if x['currentPath']=='database/setup/'+name)
        digest=hashlib.sha256(raw).hexdigest()
        if digest!=expected:raise m.SafetyError('Setup SQL differs from the rehearsed artifact')
        result[name]=[s.strip() for s in re.sub(r'--[^\n]*','',raw.decode('utf-8')).split(';') if s.strip()]
        hashes[name]=digest
    create,grant=result['002_fooddelivery_app.sql']
    if create!="CREATE USER 'fooddelivery_app'@'127.0.0.1' IDENTIFIED BY RANDOM PASSWORD" or grant!="GRANT SELECT, INSERT, UPDATE, DELETE ON `fooddelivery`.* TO 'fooddelivery_app'@'127.0.0.1'":
        raise m.SafetyError('Unexpected account setup scope')
    if len(result['003_cod.sql'])!=1 or not result['003_cod.sql'][0].startswith('INSERT INTO payment_methods '):
        raise m.SafetyError('Unexpected COD setup scope')
    return create+';',grant+';',result['003_cod.sql'][0]+';',hashes

def counts(client):
    return {name:int(client.run('SELECT COUNT(*) FROM `'+name+'`')) for name in json.loads(m.MANIFEST.read_text(encoding='utf-8'))['tableOrder']}

def current(client):
    state=m.inspect(client);m.guard(state,'main',UUID,False);schema=m.verify(client)
    if client.run('SELECT CURRENT_USER()')!='root@localhost':raise m.SafetyError('Unexpected setup operator')
    return {'schema':schema,'rowCounts':counts(client)}

def app_grants(client):
    rows=[json.loads(s) for s in client.run("SELECT JSON_OBJECT('database',TABLE_SCHEMA,'privilege',PRIVILEGE_TYPE,'grantable',IS_GRANTABLE) FROM information_schema.schema_privileges WHERE grantee="+"CONCAT(QUOTE('fooddelivery_app'),'@',QUOTE('127.0.0.1')) ORDER BY privilege_type").splitlines()]
    if len(rows)!=4 or {x['privilege'] for x in rows}!=PRIVILEGES or any(x['database']!='fooddelivery' or x['grantable']!='NO' for x in rows):
        raise m.SafetyError('Application schema privileges differ from the four approved DML rights')
    global_rows=client.run("SELECT PRIVILEGE_TYPE FROM information_schema.user_privileges WHERE grantee=CONCAT(QUOTE('fooddelivery_app'),'@',QUOTE('127.0.0.1'))").splitlines()
    if set(global_rows)-{'USAGE'}:raise m.SafetyError('Unexpected global privileges')
    if client.run("SELECT COUNT(*) FROM mysql.role_edges WHERE TO_USER='fooddelivery_app'")!='0':raise m.SafetyError('Unexpected inherited roles')
    if client.run("SELECT COUNT(*) FROM mysql.global_grants WHERE USER='fooddelivery_app'")!='0':raise m.SafetyError('Unexpected dynamic grants')
    grants=client.run('SHOW GRANTS FOR '+ACTOR).splitlines()
    if any(re.search(r'IDENTIFIED|PASSWORD|AUTHENTICATION',s,re.I) for s in grants):raise m.SafetyError('Unexpected authentication fields in grant output; withheld')
    if len(grants)!=2 or any('WITH GRANT OPTION' in s for s in grants):raise m.SafetyError('Unexpected grant clauses')
    return {'schemaPrivileges':rows,'globalPrivileges':global_rows,'roleCount':0,'dynamicGrantCount':0,'showGrants':grants}

def prepare(jar,work):
    cp,proof=jpa.prepare(jar,work/'jpa')
    source=Path(__file__).with_name('MainPaymentMethodReadCheck.java')
    r=subprocess.run([str(jpa.JAVA_HOME/'bin/javac.exe'),'-cp',cp,'-d',str(work/'jpa/helper-classes'),str(source)],capture_output=True)
    if r.returncode:raise m.SafetyError('Application payment checker compile failed; output withheld')
    proof.update(classpath=cp,paymentCheckerSha256=hashlib.sha256(source.read_bytes()).hexdigest())
    return proof

def check_app(mode,credential,prepared):
    options=configparser.ConfigParser(interpolation=None);options.read(credential,encoding='utf-8')
    if options['client']['user']!=APP or options['client']['host']!='127.0.0.1' or options['client']['port']!='3306' or options['client']['database']!='fooddelivery':
        raise m.SafetyError('Unexpected application credential target')
    password=json.loads(options['client']['password'])
    payload=base64.b64encode(APP.encode())+b'\n'+base64.b64encode(password.encode('utf-8'))+b'\n';del password;options.clear()
    r=subprocess.run([str(jpa.JAVA_HOME/'bin/java.exe'),'-Dorg.jboss.logging.provider=slf4j','-cp',prepared['classpath'],'MainPaymentMethodReadCheck',mode,UUID],input=payload,capture_output=True);del payload
    messages=[json.loads(s) for s in r.stdout.decode('utf-8',errors='replace').splitlines() if s.startswith('{"status":')]
    allowed={'status','mode','account','tcp','tlsRequired','jdbcReadOnly','rootUsedAsBackend','entitiesValidated','activeCodChoices','findByIdUsableByPaymentService','checkoutCompleted','businessEntitiesPersisted','webServerStarted','errorType','detailsWithheld'}
    if r.returncode or not messages or messages[-1]['status']!='PASS' or any(set(x)-allowed for x in messages):
        raise m.SafetyError('App-account JDBC/repository check failed; raw credential/JDBC details withheld')
    return messages[-1]

def credential_text(password):
    if len(password)!=32 or any(ord(c)<32 for c in password):raise m.SafetyError('Unexpected generated credential representation')
    value='"'+password.replace('\\','\\\\').replace('"','\\"')+'"'
    return '[client]\nhost=127.0.0.1\nport=3306\nprotocol=tcp\nuser=fooddelivery_app\npassword='+value+'\ndatabase=fooddelivery\nssl-mode=REQUIRED\ndefault-character-set=utf8mb4\n'

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--work-directory',type=Path,required=True);p.add_argument('--application-jar',type=Path,required=True)
    p.add_argument('--credential-output',type=Path);p.add_argument('--apply',action='store_true');p.add_argument('--acknowledge')
    args=p.parse_args();work=args.work_directory.resolve();credential=args.credential_output.resolve() if args.credential_output else None
    if work.is_relative_to(m.ROOT) or not work.is_dir():raise m.SafetyError('Prepare an external protected work directory')
    if args.apply and (credential is None or credential.is_relative_to(m.ROOT) or credential.exists() or not credential.parent.is_dir() or args.acknowledge!='fooddelivery_app+COD@127.0.0.1:3306/fooddelivery'):
        raise m.SafetyError('New external protected credential file and exact acknowledgement required')
    journal=work/('setup-attempt.json' if args.apply else 'prepare-result.json')
    result={'status':'STARTED','time':datetime.now(timezone(timedelta(hours=7))).isoformat(),'accountCreateSubmitted':False,'accountCreated':False,'credentialSavedOutsideGit':False,'grantsApplied':False,'codInserted':False,'baselineRun':False,'adminBootstrapRun':False,'websiteStarted':False,'test3307Accessed':False}
    with journal.open('x',encoding='utf-8') as stream:json.dump(result,stream,indent=2)
    def save():journal.write_text(json.dumps(result,indent=2),encoding='utf-8')
    try:
        root=m.Client(None,3306,'fooddelivery',login_path='fooddelivery_main')
        before=current(root)
        if any(before['rowCounts'].values()):raise m.SafetyError('Expected all sixteen Main tables empty before first setup')
        if root.run("SELECT COUNT(*) FROM mysql.user WHERE user='fooddelivery_app'")!='0':raise m.SafetyError('Account name already exists; no reset/recreate permitted')
        if root.run('SELECT @@mandatory_roles').strip():raise m.SafetyError('Mandatory roles need review before minimal-privilege setup')
        result['before']=before
        create,grant,cod,hashes=scripts();result['setupSqlHashes']=hashes
        prepared=prepare(args.application_jar.resolve(),work);result['checker']={k:v for k,v in prepared.items() if k!='classpath'}
        if not args.apply:result['status']='PREPARE_PASS';return
        # Reserve the protected file BEFORE CREATE USER; stop if filesystem access fails.
        with credential.open('x',encoding='utf-8') as secret:
            result['accountCreateSubmitted']=True;save()
            raw=root.run('SET SESSION generated_random_password_length=32;\n'+create)
            result['accountCreated']=True;save()
            rows=raw.splitlines();fields=rows[0].split('\t') if len(rows)==1 else []
            if len(fields)<3 or fields[0]!=APP or fields[1]!='127.0.0.1':raise m.SafetyError('Unexpected account creation response; output withheld')
            secret.write(credential_text(fields[2]));secret.flush();os.fsync(secret.fileno())
            result['credentialSavedOutsideGit']=True;result['generatedPasswordLength']=32;save()
            del raw,rows,fields
        root.run(grant);result['grantsApplied']=True;save()
        result['grants']=app_grants(root);save()
        result['appTcpProbe']=check_app('probe',credential,prepared);save()
        # No rewrite/upsert if COD appears concurrently. UNIQUE protects against duplicates.
        if root.run('SELECT COUNT(*) FROM payment_methods')!='0':raise m.SafetyError('Unexpected payment method appeared; stop before insert')
        root.run('START TRANSACTION;\n'+cod+'\nCOMMIT;')
        result['codInserted']=True;save()
        result['codRepositoryReadCheck']=check_app('cod',credential,prepared);save()
        after=current(root);expected=dict(before['rowCounts']);expected['payment_methods']=1
        if after['rowCounts']!=expected:raise m.SafetyError('Unexpected business/auth rows after COD setup')
        result['cod']=json.loads(root.run("SELECT JSON_OBJECT('id',method_id,'code',method_code,'name',method_name,'active',CAST(is_active AS UNSIGNED)) FROM payment_methods"))
        if result['cod']['code']!='COD' or result['cod']['name']!='Thanh toán khi nhận hàng' or result['cod']['active']!=1:raise m.SafetyError('COD row differs from approved reference data')
        result['after']=after;result['schemaUnchanged']=before['schema']==after['schema'];result['status']='PASS'
    except m.SafetyError as e:
        result.update(status='FAIL',reason=str(e),automaticRetry=False,automaticReset=False,automaticDrop=False)
        if result['accountCreateSubmitted']:
            try:result['actualAccountCount']=int(root.run("SELECT COUNT(*) FROM mysql.user WHERE user='fooddelivery_app'"));result['actualRowCounts']=counts(root)
            except Exception:result['actualStateUnavailable']=True
        raise
    except Exception:
        result.update(status='FAIL',reason='Unexpected failure; raw credential output withheld',automaticRetry=False,automaticReset=False,automaticDrop=False);raise
    finally:
        save();print(json.dumps({k:v for k,v in result.items() if k not in ['before','after','grants','checker']}))

if __name__=='__main__':
    try:main()
    except Exception:sys.exit(1)
